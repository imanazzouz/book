-- Phase 3 — extensions, UUIDv7 defaults and integrity guards.
-- Hand-written (drizzle-kit cannot express extensions, plpgsql or triggers).
-- Safe to run on an empty database and idempotent where practical.

-- ---------------------------------------------------------------------------
-- 1. Extensions
-- ---------------------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS pgcrypto; -- gen_random_bytes()
CREATE EXTENSION IF NOT EXISTS pg_trgm; -- trigram GIN indexes for search
CREATE EXTENSION IF NOT EXISTS unaccent; -- accent-insensitive matching

-- ---------------------------------------------------------------------------
-- 2. Time-ordered primary keys (UUID v7) generated by the database
-- ---------------------------------------------------------------------------
-- Keeps `id` monotonic per insert so btree indexes stay compact, and lets raw
-- SQL (seeds, admin tooling, psql) insert rows without supplying an id.
-- The application also generates v7 ids in TypeScript (src/lib/id.ts); the
-- database default is the safety net, not the normal path.
CREATE OR REPLACE FUNCTION app_uuid_v7() RETURNS uuid
  LANGUAGE plpgsql
  VOLATILE
AS $$
DECLARE
  ts_ms bigint := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
  b bytea;
BEGIN
  -- int8send is big-endian; the low 6 bytes carry the 48-bit millisecond stamp.
  b := substring(int8send(ts_ms) FROM 3) || gen_random_bytes(10);
  b := set_byte(b, 6, (get_byte(b, 6) & 15) | 112); -- version 7
  b := set_byte(b, 8, (get_byte(b, 8) & 63) | 128); -- RFC 4122 variant
  RETURN (
    encode(substring(b FROM 1 FOR 4), 'hex') || '-' ||
    encode(substring(b FROM 5 FOR 2), 'hex') || '-' ||
    encode(substring(b FROM 7 FOR 2), 'hex') || '-' ||
    encode(substring(b FROM 9 FOR 2), 'hex') || '-' ||
    encode(substring(b FROM 11 FOR 6), 'hex')
  )::uuid;
END;
$$;

DO $$
DECLARE
  t record;
BEGIN
  FOR t IN
    SELECT table_name
    FROM information_schema.columns
    WHERE table_schema = 'public' AND column_name = 'id' AND data_type = 'uuid'
  LOOP
    EXECUTE format(
      'ALTER TABLE public.%I ALTER COLUMN id SET DEFAULT app_uuid_v7()',
      t.table_name
    );
  END LOOP;
END;
$$;

-- ---------------------------------------------------------------------------
-- 3. Append-only audit trail
-- ---------------------------------------------------------------------------
-- The audit log is the legal record of every privileged action. It is enforced
-- at the database level (not only in application code) so a compromised app
-- role still cannot rewrite history.
CREATE OR REPLACE FUNCTION app_forbid_mutation() RETURNS trigger
  LANGUAGE plpgsql
AS $$
BEGIN
  RAISE EXCEPTION 'table % is append-only: % is not allowed', TG_TABLE_NAME, TG_OP
    USING ERRCODE = '42501';
END;
$$;

DROP TRIGGER IF EXISTS audit_logs_append_only ON audit_logs;
CREATE TRIGGER audit_logs_append_only
  BEFORE UPDATE OR DELETE ON audit_logs
  FOR EACH ROW EXECUTE FUNCTION app_forbid_mutation();

DROP TRIGGER IF EXISTS audit_logs_no_truncate ON audit_logs;
CREATE TRIGGER audit_logs_no_truncate
  BEFORE TRUNCATE ON audit_logs
  FOR EACH STATEMENT EXECUTE FUNCTION app_forbid_mutation();

-- ---------------------------------------------------------------------------
-- 4. updated_at maintained by the database
-- ---------------------------------------------------------------------------
-- Drizzle already sets updated_at in the application ($onUpdate); this trigger makes
-- the invariant true for raw SQL and for future services.
CREATE OR REPLACE FUNCTION app_touch_updated_at() RETURNS trigger
  LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DO $$
DECLARE
  t record;
BEGIN
  FOR t IN
    SELECT table_name
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND column_name = 'updated_at'
      AND table_name <> 'audit_logs'
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.%I', t.table_name || '_touch_updated_at', t.table_name);
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION app_touch_updated_at()',
      t.table_name || '_touch_updated_at',
      t.table_name
    );
  END LOOP;
END;
$$;

-- ---------------------------------------------------------------------------
-- 5. Accent-insensitive search normalisation
-- ---------------------------------------------------------------------------
-- `unaccent(text)` is STABLE because a dictionary could be reloaded; the wrapper is
-- declared IMMUTABLE so it can be indexed. The dictionary is fixed at build time and
-- never edited at runtime, which is the documented assumption behind this wrapper.
CREATE OR REPLACE FUNCTION app_normalize(input text) RETURNS text
  LANGUAGE sql
  IMMUTABLE
  PARALLEL SAFE
  RETURNS NULL ON NULL INPUT
AS $$ SELECT lower(public.unaccent('public.unaccent'::regdictionary, input)) $$;

CREATE INDEX IF NOT EXISTS products_name_trgm_idx
  ON products USING gin (app_normalize(name) gin_trgm_ops);
CREATE INDEX IF NOT EXISTS products_description_trgm_idx
  ON products USING gin (app_normalize(description) gin_trgm_ops);
CREATE INDEX IF NOT EXISTS stores_name_trgm_idx
  ON stores USING gin (app_normalize(name) gin_trgm_ops);
CREATE INDEX IF NOT EXISTS categories_name_ar_trgm_idx
  ON categories USING gin (app_normalize(name_ar) gin_trgm_ops);
CREATE INDEX IF NOT EXISTS categories_name_fr_trgm_idx
  ON categories USING gin (app_normalize(name_fr) gin_trgm_ops);
CREATE INDEX IF NOT EXISTS wilayas_name_fr_trgm_idx
  ON wilayas USING gin (app_normalize(name_fr) gin_trgm_ops);
CREATE INDEX IF NOT EXISTS communes_name_fr_trgm_idx
  ON communes USING gin (app_normalize(name_fr) gin_trgm_ops);
